// Matches seeded members to people in your Slack workspace by name and prints SQL that
// fills in their email + Slack user id, so they link up automatically on first sign-in
// and receive Social Exchange notifications.
//
//   SLACK_BOT_TOKEN=xoxb-... node scripts/link-slack-members.mjs > slack-links.sql
//
// Needs the bot scopes users:read and users:read.email. Review the output, then run it in the
// Supabase SQL editor. Anyone not matched is listed on stderr: add them by hand.
import fs from "node:fs";

const token = process.env.SLACK_BOT_TOKEN;
if (!token) {
  console.error("Set SLACK_BOT_TOKEN first.");
  process.exit(1);
}

const seed = fs.readFileSync(new URL("../supabase_social_exchange_seed.sql", import.meta.url), "utf8");
const memberBlock = seed.split("as v(full_name)")[0];
const members = [...memberBlock.matchAll(/^  \('((?:[^']|'')+)'\)/gm)].map((match) => match[1].replace(/''/g, "'"));

const slackUsers = [];
let cursor = "";
do {
  const url = new URL("https://slack.com/api/users.list");
  url.searchParams.set("limit", "200");
  if (cursor) url.searchParams.set("cursor", cursor);
  const body = await (await fetch(url, { headers: { Authorization: `Bearer ${token}` } })).json();
  if (!body.ok) {
    console.error(`Slack error: ${body.error}`);
    process.exit(1);
  }
  slackUsers.push(...body.members.filter((user) => !user.deleted && !user.is_bot && user.profile?.email));
  cursor = body.response_metadata?.next_cursor ?? "";
} while (cursor);

const norm = (value) => value.toLowerCase().replace(/\s+/g, " ").trim();
const byName = new Map();
for (const user of slackUsers) {
  for (const name of [user.real_name, user.profile.real_name, user.profile.display_name]) {
    if (name) byName.set(norm(name), user);
  }
}
const esc = (value) => value.replace(/'/g, "''");

const unmatched = [];
console.log("-- Generated by scripts/link-slack-members.mjs. Review before running.");
for (const name of members) {
  const user = byName.get(norm(name));
  if (!user) {
    unmatched.push(name);
    continue;
  }
  console.log(
    `update public.members set email = '${esc(user.profile.email.toLowerCase())}', slack_user_id = '${user.id}' ` +
      `where lower(full_name) = lower('${esc(name)}') and user_id is null;`
  );
}

if (unmatched.length) {
  console.error(`\nNo exact Slack match for ${unmatched.length} member(s):\n  ${unmatched.join("\n  ")}`);
}
